#!/usr/bin/env python
"""Generate the self-contained evaluation kit folder (default: reid_eval_kit/) from the sources of this repository.

The kit contains only the evaluation side (loader, split, accumulation, metrics, reports, comparison, universal runner, generic template
exporter): no FastReID / CLIP code, no encoders. Run after changing reid_eval/ so the committed kit stays in sync (tests check this).
"""
import argparse
import hashlib
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PACKAGES = ("reid_data", "reid_eval")
EXCLUDE_DIRS = {"encoders", "__pycache__"}
SCRIPTS = ("run_eval.py", "evaluate.py", "make_split.py", "export_templates.py", "compare_models.py", "selftest.py")
CONFIGS = ("bins_v1.yaml", "bins_v2.yaml", "bins_v3.yaml")
DOCS = {"eval_kit_src/README.md": "README.md", "eval_kit_src/TEMPLATE_FORMAT.md": "TEMPLATE_FORMAT.md",
        "eval_kit_src/DATASET_FORMAT.md": "DATASET_FORMAT.md", "eval_kit_src/requirements.txt": "requirements.txt"}
MARKER = ".reid_eval_kit"


def kit_files():
    """{relative path in the kit: source path}"""
    files = {}
    for pkg in PACKAGES:
        for p in sorted((ROOT / pkg).rglob("*")):
            rel = p.relative_to(ROOT)
            if p.is_file() and not (set(rel.parts) & EXCLUDE_DIRS) and p.suffix in (".py",):
                files[str(rel)] = p
    for s in SCRIPTS:
        files[s] = ROOT / s
    for c in CONFIGS:
        files[f"configs/{c}"] = ROOT / "configs" / c
    for src, dst in DOCS.items():
        files[dst] = ROOT / src
    return files


def build(out):
    out = Path(out)
    if out.exists():
        if not (out / MARKER).exists():
            raise SystemExit(f"{out} exists and is not a generated kit (no {MARKER}); refusing to overwrite it")
        shutil.rmtree(out)
    for rel, src in kit_files().items():
        dst = out / rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(src, dst)
    digest = hashlib.sha256()
    for rel in sorted(kit_files()):
        digest.update(rel.encode() + (out / rel).read_bytes())
    (out / MARKER).write_text(f"generated by tools/build_eval_kit.py; content sha256 {digest.hexdigest()}\n")
    return out


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default=str(ROOT / "reid_eval_kit"))
    a = ap.parse_args(argv)
    out = build(a.out)
    n = sum(1 for _ in kit_files())
    print(f"built {out} ({n} files)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
